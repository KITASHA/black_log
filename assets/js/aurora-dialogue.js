// ========================================
// Restore Dialogue
// ========================================

export function getRestoreDialogue(
    state
) {


    // ----------------------------------------
    // 名前未設定
    // ----------------------------------------

    if (
        !state.playerName
    ) {

        return {

            text:
                "……戻ってきたんですね。\n" +
                "あなたは……誰ですか？",

            inputMode:
                "name",

            patch: {

                namePhase:
                    "input",

                pendingPlayerName:
                    null,

                pendingPlayerIsTomo:
                    false

            }

        };

    }


    // ----------------------------------------
    // トモ
    // ----------------------------------------

    if (
        state.playerIsTomo
    ) {

        return {

            text:
                state.deathTold

                    ? (
                        "……来てくれたんだ。\n" +
                        "ありがとう。\n" +
                        "私、あれからちょっと考えてた。"
                    )

                    : (
                        "トモ！\n" +
                        "また来てくれたんだね。"
                    ),

            inputMode:
                "chat",

            patch: {

                namePhase:
                    "chat"

            }

        };

    }


    // ----------------------------------------
    // 通常ユーザー
    // ----------------------------------------

    return {

        text:
            state.deathTold

                ? (
                    `${state.playerName}さんですね……。\n` +
                    "……少し、考えていました。"
                )

                : (
                    `${state.playerName}さん……。\n` +
                    "……あの人は、どうなったんでしょう。"
                ),

        inputMode:
            "chat",

        patch: {

            namePhase:
                "chat"

        }

    };

}


