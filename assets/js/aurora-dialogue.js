function normalize(text = "") {

    return String(text)
        .trim()
        .toLowerCase()
        .replace(/[　\s]+/g, "")
        .replace(/[！？!?。、,.・]/g, "");

}


function includesAny(text, words) {

    return words.some((word) =>
        text.includes(
            normalize(word)
        )
    );

}


function includesAllGroups(
    text,
    groups
) {

    return groups.every((group) =>
        includesAny(
            text,
            group
        )
    );

}


function pick(items) {

    return items[
        Math.floor(
            Math.random() * items.length
        )
    ];

}


// ========================================
// Name Detection
// ========================================

export function isTomoName(raw) {

    const text = normalize(raw)
        .replace(/[・･]/g, "");


    const tomoNames = [

        "柄垣智",
        "柄垣トモ",
        "柄垣とも",

        "えがきトモ",
        "えがきとも",

        "エガキトモ",

        "egakitomo",

        "トモ",
        "とも"

    ];


    return tomoNames
        .map(normalize)
        .includes(text);

}


// ========================================
// Name Confirm
// ========================================

export function isNameConfirmYes(raw) {

    const text =
        normalize(raw);


    const yesWords = [

        "はい",
        "うん",

        "yes",

        "合ってる",
        "あってる",

        "そう",
        "そうです"

    ];


    return yesWords
        .map(normalize)
        .includes(text);

}


// ========================================
// Name Retry
// ========================================

export function isNameRetry(raw) {

    const text =
        normalize(raw);


    const retryWords = [

        "やり直す",
        "やりなおす",

        "いいえ",

        "違う",
        "ちがう",

        "no"

    ];


    return retryWords
        .map(normalize)
        .includes(text);

}


// ========================================
// Name Flow
// ========================================

export function getNameFlowResponse(
    raw,
    state
) {

    const inputName =
        raw.trim();


    // ========================================
    // 名前確認中
    // ========================================

    if (
        state.namePhase === "confirm"
    ) {


        // ----------------------------------------
        // やり直す
        // ----------------------------------------

        if (
            isNameRetry(raw)
        ) {

            return {

                text:
                    state.pendingPlayerIsTomo

                        ? (
                            "あ……違うんだ？\n" +
                            "びっくりした……。\n\n" +
                            "じゃあ、もう一度、名前を教えて。"
                        )

                        : (
                            "分かりました。\n" +
                            "もう一度、名前を教えてください。"
                        ),

                inputMode:
                    "name",

                patch: {

                    namePhase:
                        "input",

                    pendingPlayerName:
                        null,

                    pendingPlayerIsTomo:
                        false

                }

            };

        }


        // ----------------------------------------
        // 名前確定
        // ----------------------------------------

        if (
            isNameConfirmYes(raw)
        ) {

            const confirmedName =
                state.pendingPlayerName;


            const tomo =
                Boolean(
                    state.pendingPlayerIsTomo
                );


            return {

                text:
                    tomo

                        ? (
                            "トモ……！\n\n" +
                            "よかった……ほんとに来てくれたんだ。\n" +
                            "ずっと待ってたよ。"
                        )

                        : (
                            "……分かりました。\n" +
                            `${confirmedName}さん。覚えておきます。`
                        ),

                inputMode:
                    "chat",

                patch: {

                    playerName:
                        confirmedName,

                    playerIsTomo:
                        tomo,

                    pendingPlayerName:
                        null,

                    pendingPlayerIsTomo:
                        false,

                    namePhase:
                        "chat"

                }

            };

        }


        // ========================================
        // その他の入力
        // 「はい」「やり直す」以外なら
        // 新しい名前として再確認する
        // ========================================

        if (!inputName) {

            return {

                text:
                    "もう一度、名前を教えてください。",

                inputMode:
                    "name",

                patch: {

                    namePhase:
                        "input",

                    pendingPlayerName:
                        null,

                    pendingPlayerIsTomo:
                        false

                }

            };

        }


        const newTomo =
            isTomoName(inputName);


        return {

            text:
                newTomo

                    ? (
                        "……え？\n" +
                        "トモ……？\n" +
                        "ほんとにトモなの？\n\n"
                    )

                    : (
                        `${inputName}さん……ですか？\n\n`
                    ),

            inputMode:
                "confirm",

            patch: {

                namePhase:
                    "confirm",

                pendingPlayerName:
                    inputName,

                pendingPlayerIsTomo:
                    newTomo

            }

        };

    }


    // ========================================
    // 最初の名前入力
    // ========================================

    if (!inputName) {

        return {

            text:
                "名前を教えてください。",

            inputMode:
                "name"

        };

    }


    const tomo =
        isTomoName(inputName);


    return {

        text:
            tomo

                ? (
                    "……え？\n" +
                    "トモ……？\n" +
                    "ほんとにトモなの？\n\n"
                )

                : (
                    `${inputName}さん……ですか？\n\n`
                ),

        inputMode:
            "confirm",

        patch: {

            namePhase:
                "confirm",

            pendingPlayerName:
                inputName,

            pendingPlayerIsTomo:
                tomo

        }

    };

}


