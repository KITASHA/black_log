// ========================================
// Response Helper
// ========================================

function response(
    normal,
    tomo,
    state,
    patch = null
) {

    return {

        text:
            state.playerIsTomo
                ? tomo
                : normal,

        patch

    };

}


// ========================================
// Death Detection
// ========================================

function isDeathClaim(text) {

    return includesAllGroups(
        text,
        [

            [
                "トモ",
                "柄垣",
                "えがき",
                "あの人"
            ],

            [
                "死んだ",
                "死亡",
                "亡くなった",
                "亡くなって",
                "死んで"
            ]

        ]
    );

}


